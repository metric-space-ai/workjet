export const GLYPH_W = 5;
export const GLYPH_H = 7;

export function textWidth(text, scale = 1, tracking = 1) {
  return text.length * (GLYPH_W + tracking) * scale - tracking * scale;
}

/** Text ins Bitmap setzen; unbekannte Zeichen werden uebersprungen. */
export function drawText(bmp, text, x, y, scale, level, setPixel, tracking = 1) {
  let cx = x;
  for (const raw of String(text)) {
    const ch = raw.toUpperCase();
    const glyph = FONT[ch] || FONT[raw] || null;
    if (glyph) {
      for (let row = 0; row < GLYPH_H; row += 1) {
        for (let col = 0; col < GLYPH_W; col += 1) {
          if (glyph[row][col] !== '1') continue;
          for (let dy = 0; dy < scale; dy += 1) {
            for (let dx = 0; dx < scale; dx += 1) {
              setPixel(bmp, cx + col * scale + dx, y + row * scale + dy, level);
            }
          }
        }
      }
    }
    cx += (GLYPH_W + tracking) * scale;
  }
  return cx;
}
