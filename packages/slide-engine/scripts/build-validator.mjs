// Bundles src/validator/cli.ts into dist/slide-engine-validator.mjs, the single-file Node
// validator that CTOX vendors. Deterministic: same sources and esbuild version, same bytes.
import * as NodeCrypto from "node:crypto";
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";
import * as NodeURL from "node:url";

import * as esbuild from "esbuild";

const ESBUILD_VERSION = "0.28.1";
const packageRoot = NodePath.resolve(
  NodePath.dirname(NodeURL.fileURLToPath(import.meta.url)),
  "..",
);
const outfile = NodePath.join(packageRoot, "dist", "slide-engine-validator.mjs");
const forbiddenPackage = /(?:^|\/)node_modules\/(?:react|react-dom|three)\//;

if (esbuild.version !== ESBUILD_VERSION) {
  console.error(
    `build-validator: esbuild ${esbuild.version} resolved; ${ESBUILD_VERSION} is required.`,
  );
  process.exit(1);
}

const result = await esbuild.build({
  absWorkingDir: packageRoot,
  entryPoints: ["src/validator/cli.ts"],
  outfile,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  minify: false,
  sourcemap: false,
  charset: "utf8",
  legalComments: "eof",
  metafile: true,
  logLevel: "warning",
  banner: {
    js: "// @workjet/slide-engine validator. Generated by packages/slide-engine/scripts/build-validator.mjs; do not edit.",
  },
});

const forbidden = Object.keys(result.metafile.inputs).filter((input) =>
  forbiddenPackage.test(input),
);
if (forbidden.length > 0) {
  console.error(
    `build-validator: the bundle must not include react or three:\n${forbidden.join("\n")}`,
  );
  process.exit(1);
}

const bytes = NodeFS.readFileSync(outfile);
const sha256 = NodeCrypto.createHash("sha256").update(bytes).digest("hex");
console.log(
  `${NodePath.relative(packageRoot, outfile)}  sha256=${sha256}  bytes=${bytes.length}  esbuild=${esbuild.version}`,
);
